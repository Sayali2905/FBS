x = 10
y = 20

##Relational op

#1. == (exact equals to)  (works on different data types)
print(x == 10)      ## True
print(x == '10')    ## False

#2. !=  (works on different data types)
print(x != y)       ## True

#3. >
print(x > 5)        ## True

#4. >= (greater than equals to)
print(x >= 10)      ## True
print(x >= y)       ## False

#5. < 
print(y < x)        ## False

#6. <=
print(y <= 20)      ## True